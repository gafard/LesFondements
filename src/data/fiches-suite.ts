import type { Fiche, Question, Section } from './fiches';

type SectionInput = [title: string, content: string];

function buildFiche(
  id: number,
  title: string,
  subtitle: string,
  icon: string,
  sections: SectionInput[],
  essential: string,
  questions: string[],
  lectures: string[],
): Fiche {
  const mappedSections: Section[] = sections.map(([sectionTitle, content]) => ({
    title: sectionTitle,
    content,
    versets: [],
  }));

  const mappedQuestions: Question[] = questions.map((text, index) => ({
    id: `${id}_${index + 1}`,
    text,
  }));

  return {
    id,
    title,
    subtitle,
    icon,
    sections: mappedSections,
    summary: [{ title: "L'essentiel à retenir", content: essential, versets: [] }],
    questions: mappedQuestions,
    lectures,
  };
}

